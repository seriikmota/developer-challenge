-- Idempotency of POST /requests: the key is scoped by user and stored in the same transaction as the creation.
-- Same key and same payload hash replays the stored response; same key and another hash is a 409.

CREATE TABLE idempotency_key (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES app_user (id),
    idem_key        VARCHAR(100) NOT NULL,
    request_hash    VARCHAR(64) NOT NULL,
    response_status INTEGER     NOT NULL,
    response_body   TEXT        NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_idempotency_key_user_key UNIQUE (user_id, idem_key)
);

-- supports the cleanup of keys older than the retention window (at least 24 h)
CREATE INDEX ix_idempotency_key_created_at ON idempotency_key (created_at);
