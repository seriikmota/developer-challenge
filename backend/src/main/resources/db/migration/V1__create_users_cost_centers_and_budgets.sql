-- Users, cost centers and monthly budgets.
-- Enums are stored as VARCHAR with CHECK constraints (mapped with @Enumerated(STRING)).

CREATE TABLE cost_center (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL,
    name       VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_cost_center_code UNIQUE (code)
);

CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(120) NOT NULL,
    email          VARCHAR(254) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    approver_level VARCHAR(10),
    cost_center_id BIGINT REFERENCES cost_center (id),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_app_user_role CHECK (role IN ('SOLICITANTE', 'APROVADOR', 'ADMIN')),
    CONSTRAINT ck_app_user_approver_level CHECK (approver_level IN ('NIVEL_1', 'NIVEL_2')),
    -- only APROVADOR has a level, and every APROVADOR has one
    CONSTRAINT ck_app_user_level_by_role CHECK ((role = 'APROVADOR') = (approver_level IS NOT NULL)),
    -- every user belongs to a cost center; only ADMIN may be global
    CONSTRAINT ck_app_user_cost_center CHECK (role = 'ADMIN' OR cost_center_id IS NOT NULL)
);

-- emails are compared case-insensitively
CREATE UNIQUE INDEX uk_app_user_email ON app_user (lower(email));
CREATE INDEX ix_app_user_cost_center ON app_user (cost_center_id);

-- One row per cost center and competence month (first day of the month).
-- A month without a row has zero budget.
CREATE TABLE monthly_budget (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cost_center_id BIGINT        NOT NULL REFERENCES cost_center (id),
    month          DATE          NOT NULL,
    amount         NUMERIC(19, 2) NOT NULL,
    consumed       NUMERIC(19, 2) NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_monthly_budget_cost_center_month UNIQUE (cost_center_id, month),
    CONSTRAINT ck_monthly_budget_first_day CHECK (EXTRACT(DAY FROM month) = 1),
    CONSTRAINT ck_monthly_budget_amount CHECK (amount >= 0),
    -- safety net: the balance can never be negative, even if a query is wrong
    CONSTRAINT ck_monthly_budget_consumed CHECK (consumed >= 0 AND consumed <= amount)
);
