-- Audit history: one row per action on a request. Append-only, enforced by the database.

CREATE TABLE request_event (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id        BIGINT      NOT NULL REFERENCES purchase_request (id),
    version_number    INTEGER     NOT NULL,
    step_order        INTEGER,
    actor_id          BIGINT      NOT NULL REFERENCES app_user (id),
    actor_role        VARCHAR(20) NOT NULL,
    action            VARCHAR(20) NOT NULL,
    from_status       VARCHAR(20),
    to_status         VARCHAR(20) NOT NULL,
    comment           VARCHAR(2000),
    request_id_header VARCHAR(100),
    occurred_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_request_event_actor_role CHECK (actor_role IN ('SOLICITANTE', 'APROVADOR', 'ADMIN')),
    CONSTRAINT ck_request_event_action CHECK (action IN ('CREATE', 'EDIT', 'SUBMIT', 'APPROVE', 'REJECT', 'REQUEST_CHANGES', 'CANCEL')),
    -- only creation has no origin status
    CONSTRAINT ck_request_event_from_status CHECK ((action = 'CREATE') = (from_status IS NULL))
);

CREATE INDEX ix_request_event_request ON request_event (request_id, occurred_at, id);

CREATE FUNCTION forbid_request_event_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'request_event is append-only: % is not allowed', TG_OP
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER trg_request_event_append_only
    BEFORE UPDATE OR DELETE ON request_event
    FOR EACH ROW EXECUTE FUNCTION forbid_request_event_change();

CREATE TRIGGER trg_request_event_no_truncate
    BEFORE TRUNCATE ON request_event
    FOR EACH STATEMENT EXECUTE FUNCTION forbid_request_event_change();
