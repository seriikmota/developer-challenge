-- Purchase requests, their versions, items and approval steps.
--
-- current_version changes only when the request is (re)submitted: v1, v2...
-- lock_version changes on every write and backs optimistic locking (JPA @Version).

CREATE TABLE purchase_request (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT      NOT NULL REFERENCES app_user (id),
    cost_center_id  BIGINT      NOT NULL REFERENCES cost_center (id),
    status          VARCHAR(20) NOT NULL,
    current_version INTEGER     NOT NULL DEFAULT 1,
    lock_version    BIGINT      NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_purchase_request_status CHECK (status IN ('DRAFT', 'PENDING_APPROVAL', 'CHANGES_REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_purchase_request_current_version CHECK (current_version >= 1)
);

CREATE INDEX ix_purchase_request_owner ON purchase_request (owner_id);
CREATE INDEX ix_purchase_request_cost_center_status ON purchase_request (cost_center_id, status);
CREATE INDEX ix_purchase_request_created_at ON purchase_request (created_at);

-- A version is editable while submitted_at is NULL and immutable after it (see trigger below).
CREATE TABLE request_version (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id       BIGINT         NOT NULL REFERENCES purchase_request (id),
    number           INTEGER        NOT NULL,
    title            VARCHAR(150)   NOT NULL,
    description      VARCHAR(2000),
    category         VARCHAR(20)    NOT NULL,
    needed_by        DATE,
    total            NUMERIC(19, 2) NOT NULL,
    submitted_at     TIMESTAMPTZ,
    competence_month DATE,
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_request_version_number UNIQUE (request_id, number),
    CONSTRAINT ck_request_version_number CHECK (number >= 1),
    CONSTRAINT ck_request_version_category CHECK (category IN ('EQUIPMENT', 'SERVICES', 'SUPPLIES', 'TRAVEL', 'SOFTWARE', 'OTHER')),
    CONSTRAINT ck_request_version_total CHECK (total >= 0),
    -- the competence month is fixed at submission
    CONSTRAINT ck_request_version_submission CHECK ((submitted_at IS NULL) = (competence_month IS NULL)),
    CONSTRAINT ck_request_version_competence_first_day CHECK (EXTRACT(DAY FROM competence_month) = 1)
);

CREATE TABLE request_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id  BIGINT         NOT NULL REFERENCES request_version (id) ON DELETE CASCADE,
    position    INTEGER        NOT NULL,
    description VARCHAR(300)   NOT NULL,
    quantity    INTEGER        NOT NULL,
    unit_price  NUMERIC(19, 2) NOT NULL,
    line_total  NUMERIC(19, 2) NOT NULL,
    -- deferred: replacing the items of a draft inserts the new rows before Hibernate deletes the old ones
    CONSTRAINT uk_request_item_position UNIQUE (version_id, position) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT ck_request_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_request_item_unit_price CHECK (unit_price > 0),
    CONSTRAINT ck_request_item_line_total CHECK (line_total = quantity * unit_price)
);

CREATE TABLE approval_step (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id  BIGINT      NOT NULL REFERENCES request_version (id),
    step_order  INTEGER     NOT NULL,
    level       VARCHAR(10) NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    decided_by  BIGINT REFERENCES app_user (id),
    decided_at  TIMESTAMPTZ,
    comment     VARCHAR(2000),
    CONSTRAINT uk_approval_step_order UNIQUE (version_id, step_order),
    -- segregation of duties: the same person never decides two steps of the same version
    CONSTRAINT uk_approval_step_decided_by UNIQUE (version_id, decided_by),
    CONSTRAINT ck_approval_step_order CHECK (step_order >= 1),
    CONSTRAINT ck_approval_step_level CHECK (level IN ('NIVEL_1', 'NIVEL_2', 'ADMIN')),
    CONSTRAINT ck_approval_step_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CHANGES_REQUESTED')),
    -- a decided step always records who decided and when
    CONSTRAINT ck_approval_step_decision CHECK ((status = 'PENDING') = (decided_by IS NULL) AND (decided_by IS NULL) = (decided_at IS NULL))
);

CREATE INDEX ix_approval_step_pending ON approval_step (version_id) WHERE status = 'PENDING';

-- Submitted versions are immutable: no update or delete of the version, no change to its items.
CREATE FUNCTION forbid_submitted_version_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF OLD.submitted_at IS NOT NULL THEN
        RAISE EXCEPTION 'request_version % (request %, v%) is submitted and cannot be changed', OLD.id, OLD.request_id, OLD.number
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_request_version_immutable
    BEFORE UPDATE OR DELETE ON request_version
    FOR EACH ROW EXECUTE FUNCTION forbid_submitted_version_change();

CREATE FUNCTION forbid_submitted_item_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
DECLARE
    target_version BIGINT := CASE WHEN TG_OP = 'INSERT' THEN NEW.version_id ELSE OLD.version_id END;
BEGIN
    IF EXISTS (SELECT 1 FROM request_version WHERE id = target_version AND submitted_at IS NOT NULL) THEN
        RAISE EXCEPTION 'items of submitted request_version % cannot be changed', target_version
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_request_item_immutable
    BEFORE INSERT OR UPDATE OR DELETE ON request_item
    FOR EACH ROW EXECUTE FUNCTION forbid_submitted_item_change();
